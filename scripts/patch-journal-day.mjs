const startMarker = '  private renderJournal(container: HTMLElement): void {';
const endMarker = '\n  private renderBrowse(container: HTMLElement): void {';
const start = source.indexOf(startMarker);
const end = source.indexOf(endMarker, start);
if (start < 0 || end < 0 || end <= start) throw new Error('Could not locate renderJournal method boundaries');
source = source.slice(0, start) + journalMethod + source.slice(end);

fs.writeFileSync(file, source);
console.log('Journal day context wired to canonical projections.');
